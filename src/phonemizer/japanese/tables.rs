static SUBSTITUTIONS: &[(&[&str], &str)] = &[
    (&["ty", "ch", "ts"], "t"),
    (&["j", "dy"], "d"),
    (&["gy"], "g"),
    (&["ky"], "k"),
    (&["py"], "p"),
    (&["ny"], "n"),
    (&["ry"], "r"),
    (&["my"], "m"),
    (&["hy", "f"], "h"),
    (&["by", "v"], "b"),
    (&["dz"], "z"),
    (&["l"], "r"),
    (&["ly"], "l"),
];

pub(super) static VOWEL_LOOKUP: LazyLock<HashMap<String, &'static str>> = LazyLock::new(|| {
    let mut map = HashMap::new();
    for &(vowel, list) in VOWEL_TABLE {
        for &kana in list {
            map.insert(kana.to_string(), vowel);
        }
    }
    map
});

pub(super) static CONSONANT_LOOKUP: LazyLock<HashMap<String, &'static str>> = LazyLock::new(|| {
    let mut map = HashMap::new();
    for &(consonant, list) in CONSONANT_TABLE {
        for &kana in list {
            map.insert(kana.to_string(), consonant);
        }
    }
    map
});

pub(super) static SUBSTITUTE_LOOKUP: LazyLock<HashMap<&'static str, &'static str>> =
    LazyLock::new(|| {
        let mut map = HashMap::new();
        for &(srcs, target) in SUBSTITUTIONS {
            for &src in srcs {
                map.insert(src, target);
            }
        }
        map
    });
